TRANSLATIONS = MappingProxyType({locale: MappingProxyType(
    {key: pair[index] for key, pair in MESSAGES.items()})
    for index, locale in enumerate(LOCALES)})


def resolve_locale(value):
    return value if value in LOCALES else DEFAULT_LOCALE


def translate(locale, key, **params):
    """Return escaped-by-Jinja text; report catalog defects without an HTTP 500."""
    locale = resolve_locale(locale)
    text = TRANSLATIONS[locale].get(key)
    if text is None:
        logger.warning("Missing Web translation: locale=%s key=%s", locale, key)
        text = TRANSLATIONS["en"].get(key, key)
    try:
        return text.format(**params)
    except (KeyError, IndexError, ValueError, TypeError):
        # Never log interpolation values: they may include operator data.
        logger.error("Invalid Web translation interpolation: locale=%s key=%s", locale, key)
        return TRANSLATIONS[locale]["error.invalid"]


def plural(locale, key, count, **params):
    return translate(locale, key + (".one" if count == 1 else ".other"), count=count, **params)


@dataclass(frozen=True)
class Message:
    key: str
    params: dict = field(default_factory=dict)
    detail: str | None = None


class WebInputError(ValueError):
    """Web-owned validation with a stable key, without changing domain errors."""
    def __init__(self, key, *, detail=None, **params):
        self.message = Message(key, params, detail)
        super().__init__(translate("en", key, **params))


def safe_return_to(value):
    """Keep a local path/query; reject URL parser and encoded redirect tricks."""
    if not isinstance(value, str) or len(value) > 2048:
        return "/"
    if re.search(r"%(?![0-9a-fA-F]{2})", value):
        return "/"
    decoded = value
    for _ in range(5):
        if (not decoded.startswith("/") or decoded.startswith("//") or "\\" in decoded
                or any(ord(ch) < 32 or ord(ch) == 127 for ch in decoded)):
            return "/"
        try:
            parts = urlsplit(decoded)
        except ValueError:
            return "/"
        if parts.scheme or parts.netloc:
            return "/"
        next_value = unquote(decoded)
        if next_value == decoded:
            return value if not any(ch.isspace() for ch in value) else "/"
        decoded = next_value
    return "/"
